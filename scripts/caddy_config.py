#!/usr/bin/env python3
"""Print the private Caddy site block using the existing setup configuration."""
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.security import proxy_token


def render(configuration):
    values = {}
    for line in configuration.splitlines():
        match = re.fullmatch(r"(APP_ORIGIN|APP_PASSWORD_HASH)='([^']*)'", line.strip())
        if match:
            values[match[1]] = match[2]
    origin = urlsplit(values.get('APP_ORIGIN', ''))
    encoded = values.get('APP_PASSWORD_HASH', '')
    if origin.scheme != 'https' or not origin.hostname or origin.username or origin.path or origin.query or origin.fragment:
        raise ValueError('Use the HTTPS .env generated by scripts/setup.py.')
    if not re.fullmatch(r'[A-Za-z0-9.-]+(?::[0-9]+)?', origin.netloc):
        raise ValueError('Invalid Caddy hostname in APP_ORIGIN.')
    if not re.fullmatch(r'pbkdf2_sha256\$600000\$[0-9a-f]{32}\$[0-9a-f]{64}', encoded):
        raise ValueError('Use the password hash generated by scripts/setup.py.')
    template = (ROOT / 'deploy' / 'Caddyfile').read_text()
    return template.replace('net-tools.humza.xyz', origin.netloc).replace('{$NET_TOOLS_PROXY_TOKEN}', proxy_token(encoded))


def main():
    try:
        print(render((ROOT / '.env').read_text()), end='')
    except (OSError, ValueError) as error:
        sys.exit(str(error))


if __name__ == '__main__':
    main()
